    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
            // 1. Obtencion de las entradas basicas
            String nombre = txtNombre.getText().trim();
            double peso = Double.parseDouble(txtIngresePeso.getText().trim());
            double altura = Double.parseDouble(txtIngresaAltura.getText().trim());
 
            if (nombre.isEmpty() || nombre.equals(PLACEHOLDER_NOMBRE)) {
                JOptionPane.showMessageDialog(this,
                        "Por favor, ingrese el nombre del paciente.",
                        "Error de entrada", JOptionPane.WARNING_MESSAGE);
                return;
            }
 
            // 2. Instanciacion del TDA: si es menor de edad se usa la
            // subclase (pacientesmenores), demostrando la HERENCIA
            pacientes paciente;
            if (chkEdad.isSelected()) {
                String textoEdad = txtEdad.getText().trim();
                if (textoEdad.isEmpty() || textoEdad.equals(PLACEHOLDER_EDAD)) {
                    JOptionPane.showMessageDialog(this,
                            "Por favor, ingrese la edad del paciente menor.",
                            "Error de entrada", JOptionPane.WARNING_MESSAGE);
                    return;
                }
                int edad = Integer.parseInt(textoEdad);
                paciente = new pacientesmenores(nombre, peso, altura, edad);
            } else {
                paciente = new pacientes(nombre, peso, altura);
            }
 
            // 3. Calculo de resultados usando la logica del TDA
            double imc = paciente.calcularIMC();
            String estado = paciente.obtenerEstadoNutricional();
 
            txtResultados.setForeground(java.awt.Color.BLACK);
            txtResultados.setText(String.format("IMC de %s: %.2f", paciente.getNombre(), imc));
 
            txtEstado.setForeground(java.awt.Color.BLACK);
            txtEstado.setText("Diagnostico: " + estado);
 
            // 4. Calculo RECURSIVO del promedio de pesos historicos,
            // solo si el usuario escribio un historial valido
            String textoHistorial = txtHistorialPeso.getText().trim();
            if (!textoHistorial.isEmpty() && !textoHistorial.equals(PLACEHOLDER_HISTORIAL)) {
                String[] partes = textoHistorial.split(",");
                double[] historial = new double[partes.length];
                for (int i = 0; i < partes.length; i++) {
                    historial[i] = Double.parseDouble(partes[i].trim());
                }
                // Este metodo usa recursion internamente (sumarPesosHistoricos)
                double promedio = paciente.calcularPromedioPesoHistorico(historial);
 
                jTextField1.setForeground(java.awt.Color.BLACK);
                jTextField1.setText(String.format("Promedio historico de peso: %.2f kg", promedio));
            } else {
                jTextField1.setForeground(java.awt.Color.BLACK);
                jTextField1.setText("Sin historial ingresado");
            }
 
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Asegurese de ingresar solo numeros en Peso, Altura, Edad e Historial (use punto para decimales).",
                    "Formato incorrecto", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            // Captura las validaciones lanzadas desde los constructores del TDA
            JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Datos invalidos", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

