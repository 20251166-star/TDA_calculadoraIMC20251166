private void agregarPlaceholder(final javax.swing.JTextField campo, final String textoPlaceholder) {
        campo.setForeground(java.awt.Color.GRAY);
        campo.setText(textoPlaceholder);
 
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (campo.getText().equals(textoPlaceholder)) {
                    campo.setText("");
                    campo.setForeground(java.awt.Color.BLACK);
                }
            }
 
            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (campo.getText().trim().isEmpty()) {
                    campo.setForeground(java.awt.Color.GRAY);
                    campo.setText(textoPlaceholder);
                }
            }
        });
    }
